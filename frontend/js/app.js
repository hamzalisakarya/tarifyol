function updateMenuLabel(isOpen) {
    const label = menuToggle?.querySelector("[data-i18n='menuLabel']");
    if (label) {
        label.textContent = isOpen
            ? (currentLanguage === "de" ? "Menü schließen" : "Menüyü kapat")
            : translations[currentLanguage].menuLabel;
    }
}

function closeMenu() {
    menuToggle?.setAttribute("aria-expanded", "false");
    headerPanel?.classList.remove("is-open");
    document.body.classList.remove("menu-open");
    updateMenuLabel(false);
}

function setLanguage(language) {
    currentLanguage = translations[language] ? language : "de";
    document.documentElement.lang = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const value = translations[currentLanguage][element.dataset.i18n];
        if (value) element.textContent = value;
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
        const value = translations[currentLanguage][element.dataset.i18nAriaLabel];
        if (value) element.setAttribute("aria-label", value);
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
        button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
    });

    try {
        localStorage.setItem(storageKey, currentLanguage);
    } catch {
        // German remains available if browser storage is disabled.
    }

    updateMenuLabel(menuToggle?.getAttribute("aria-expanded") === "true");
    if (latestEstimate) renderConsumptionEstimate(latestEstimate);
    document.dispatchEvent(new CustomEvent("tarifyol:languagechange", { detail: { language: currentLanguage } }));
}

